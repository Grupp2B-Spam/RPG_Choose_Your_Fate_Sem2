'use strict';

/**
 * Renders docs/architecture/architecture.drawio from the template and the manifest.
 *
 *   node scripts/architecture/build.js
 *
 * The template is the file you open in draw.io. The output is not: it carries a banner
 * saying so, and verify.js fails if the two disagree.
 */

const fs = require('node:fs');
const path = require('node:path');

const { loadManifest } = require('./lib/manifest.js');
const { createResolver } = require('./lib/render.js');
const { spliceTokens } = require('./lib/splice.js');

const TEMPLATE_RELATIVE = path.join('docs', 'architecture', 'architecture.template.drawio');
const MANIFEST_RELATIVE = path.join('docs', 'architecture', 'architecture.json');
const OUTPUT_RELATIVE = path.join('docs', 'architecture', 'architecture.drawio');

const BANNER =
  '<!-- GENERATED by scripts/architecture/build.js from architecture.template.drawio - do not edit -->';

/**
 * @param {{ repoRoot: string }} options
 * @returns {{ xml: string, stats: { services: number, resolved: number } }}
 */
function build({ repoRoot }) {
  const manifest = loadManifest(path.join(repoRoot, MANIFEST_RELATIVE));

  // Normalise before anything else. A template saved from draw.io on Windows arrives
  // with CRLF, and without this the output would differ byte-for-byte between machines
  // and the drift check would fail where nothing is actually wrong.
  const template = fs
    .readFileSync(path.join(repoRoot, TEMPLATE_RELATIVE), 'utf8')
    .replace(/\r\n/g, '\n');

  const { text, resolved, unresolved } = spliceTokens(template, createResolver(manifest));

  if (unresolved.length > 0) {
    throw new Error(
      `${unresolved.length} unresolved token(s) in the template:\n  ` +
        unresolved.map((t) => `{{${t}}}`).join('\n  ')
    );
  }

  const xml = withBanner(text);
  return { xml, stats: { services: manifest.services.length, resolved: resolved.length } };
}

function withBanner(text) {
  const withEnding = text.endsWith('\n') ? text : `${text}\n`;
  const declaration = /^<\?xml[^>]*\?>\n?/.exec(withEnding);
  if (!declaration) return `${BANNER}\n${withEnding}`;
  const head = declaration[0].endsWith('\n') ? declaration[0] : `${declaration[0]}\n`;
  return `${head}${BANNER}\n${withEnding.slice(declaration[0].length)}`;
}

function main() {
  const repoRoot = path.resolve(__dirname, '..', '..');
  const { xml, stats } = build({ repoRoot });
  const out = path.join(repoRoot, OUTPUT_RELATIVE);
  fs.writeFileSync(out, xml);
  process.stdout.write(
    `built ${OUTPUT_RELATIVE}: ${stats.services} nodes, ${stats.resolved} tokens resolved\n`
  );
}

if (require.main === module) main();

module.exports = { build, TEMPLATE_RELATIVE, MANIFEST_RELATIVE, OUTPUT_RELATIVE, BANNER };
